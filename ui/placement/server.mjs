#!/usr/bin/env node
// Interactive placement server (TinyUPS).
//
// A dependency-free Node HTTP server that hosts the browser UI for interactive
// component placement.  It serves:
//
//   /                 the UI (public/index.html + app.js + style.css)
//   /graph.json       build/layout/graph.json (extract.py's placement graph)
//   /api/seeds        what it can start from: build/layout (leg-*/pos-*/raw-*)
//                     and your tracked saves in placements/
//   /api/seed?name=X  one of them
//   /api/params       GET the tracked tuning (params.json); POST/PUT to write it
//   /api/save         POST -> write placements/<name>.json
//   /api/apply        POST -> run apply.py on a saved file (+ KiCad DRC)
//   /vendor/<pkg>/... node_modules for the vendored d3-force ES modules
//
// Two of those write into the repo on purpose — the tuning and your saved
// placements (history 0016); everything generated stays in build/.
//
// The placement engine itself (d3-force) runs *in the browser*, so the sim is
// live while you drag.  See ui/placement/README.md.
//
// Usage: node ui/placement/server.mjs   (PORT=4097 HOST=0.0.0.0 by default)
import { execFileSync, spawnSync } from "node:child_process";
import fs from "node:fs";
import http from "node:http";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));      // ui/placement
const ROOT = path.dirname(path.dirname(HERE));                  // repo root
const PUBLIC = path.join(HERE, "public");
const LAYOUT = path.join(ROOT, "build", "layout");
const GRAPH = path.join(LAYOUT, "graph.json");
const FEEDBACK = path.join(LAYOUT, "route-feedback.json");
// The tracked tuning file.  Unlike everything else the UI writes, this one is
// *in* the repo on purpose: the tuning is a reviewable, revertable artifact
// (see docs/history/0016-placement-ui-decisions.md).
const PARAMS = path.join(HERE, "params.json");
// Placements you save are your work product, so they are tracked too and live
// next to the app (docs/history/0016-placement-ui-decisions.md).  Everything
// *generated* (graph, boards, DRC reports) stays in build/.
const PLACEMENTS = path.join(HERE, "placements");
const VENDOR = path.join(HERE, "node_modules");
const VENDOR_PKGS = new Set(["d3-force", "d3-dispatch", "d3-quadtree", "d3-timer"]);
const PY = process.env.PYTHON || "/opt/eda/venv/bin/python";
const PORT = Number(process.env.PORT || 4097);
const HOST = process.env.HOST || "0.0.0.0";
const DEFAULT_SEED = process.env.SEED || "main";

const MIME = {
  ".html": "text/html; charset=utf-8",
  ".js": "application/javascript; charset=utf-8",
  ".mjs": "application/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".ico": "image/x-icon",
  ".map": "application/json; charset=utf-8",
};

const send = (res, code, body, type = "text/plain; charset=utf-8") => {
  res.writeHead(code, { "Content-Type": type, "Cache-Control": "no-store" });
  res.end(body);
};
const sendJSON = (res, code, obj) => send(res, code, JSON.stringify(obj), MIME[".json"]);
const safeName = (s) => /^[A-Za-z0-9._-]+$/.test(s) ? s : null;

// --- graph / seed discovery ------------------------------------------------
// The graph is derived from the board + the shared power data, so a stale
// graph.json is worse than a missing one: the UI would draw old components or
// old currents.  Rebuild when any source is newer than the graph.
const GRAPH_DEPS = [
  path.join(ROOT, "hardware", "tinyups.kicad_pcb"),
  path.join(ROOT, "hardware", "blocks.py"),
  path.join(ROOT, "hardware", "power_spec.py"),
  path.join(ROOT, "hardware", "power_map.py"),
  path.join(ROOT, "hardware", "power_report.py"),
  path.join(HERE, "extract.py"),
];
function ensureGraph() {
  let stale = !fs.existsSync(GRAPH);
  if (!stale) {
    const g = fs.statSync(GRAPH).mtimeMs;
    stale = GRAPH_DEPS.some((f) => fs.existsSync(f) && fs.statSync(f).mtimeMs > g);
  }
  if (!stale) return { ok: true };
  try {
    console.log(`graph.json ${fs.existsSync(GRAPH) ? "stale" : "missing"} -> extract.py (from the board)`);
    execFileSync(PY, [path.join(HERE, "extract.py")], { stdio: "inherit" });
    return { ok: true };
  } catch (e) {
    return { ok: false, error: String(e.message || e) };
  }
}

function listSeeds() {
  const out = [];
  const meta = (file) => {
    let engine = "?", n = 0, params = 0;
    try {
      const j = JSON.parse(fs.readFileSync(file, "utf8"));
      engine = j.engine || "?"; params = j.params ? Object.keys(j.params).length : 0;
      n = j.positions ? Object.keys(j.positions).length : 0;
    } catch { /* ignore */ }
    return { engine, n, params };
  };
  // engine output / legalised placements (untracked, regenerated by `make layout`)
  if (fs.existsSync(LAYOUT)) {
    for (const f of fs.readdirSync(LAYOUT)) {
      if (!/^(leg|pos|raw|interactive)-[\w.-]+\.json$/.test(f)) continue;
      const name = f.replace(/\.json$/, "");
      out.push({ name, ...meta(path.join(LAYOUT, f)), legal: name.startsWith("leg-"), tracked: false });
    }
  }
  // placements you saved from the UI (tracked)
  if (fs.existsSync(PLACEMENTS)) {
    for (const f of fs.readdirSync(PLACEMENTS)) {
      if (!/^[\w][\w.-]*\.json$/.test(f)) continue;
      const name = f.replace(/\.json$/, "");
      out.push({ name, ...meta(path.join(PLACEMENTS, f)), legal: false, tracked: true });
    }
  }
  // legalised first, then your own placements, then alphabetically
  out.sort((a, b) => (b.legal - a.legal) || (b.tracked - a.tracked) || a.name.localeCompare(b.name));
  return out;
}

// A seed is looked up in the tracked placements first, then in build/layout.
function seedPath(name) {
  for (const dir of [PLACEMENTS, LAYOUT]) {
    const f = path.join(dir, name + ".json");
    if (f.startsWith(dir + path.sep) && fs.existsSync(f)) return f;
  }
  return null;
}

function serveFile(res, file) {
  fs.readFile(file, (err, buf) => {
    if (err) return send(res, 404, "not found");
    send(res, 200, buf, MIME[path.extname(file).toLowerCase()] || "application/octet-stream");
  });
}

function readBody(req) {
  return new Promise((resolve, reject) => {
    let s = "";
    req.on("data", (c) => { s += c; if (s.length > 5e6) reject(new Error("body too large")); });
    req.on("end", () => resolve(s));
    req.on("error", reject);
  });
}

// --- params.json (the tracked tuning) --------------------------------------
const KEY_RE = /^[A-Z][A-Z0-9_]{0,23}$/;
const rel = (f) => path.relative(ROOT, f);

function readParams() {
  try {
    const j = JSON.parse(fs.readFileSync(PARAMS, "utf8"));
    return (j && typeof j === "object") ? j : {};
  } catch { return {}; }
}

// Keep unknown top-level keys (the file's _comment) when writing.
function writeParams(body) {
  const p = body.params;
  if (!p || typeof p !== "object" || Array.isArray(p)) throw new Error("params must be an object");
  const clean = {};
  for (const [k, v] of Object.entries(p)) {
    if (!KEY_RE.test(k)) throw new Error(`bad parameter name: ${k}`);
    if (typeof v === "boolean") clean[k] = v;
    else if (typeof v === "number" && Number.isFinite(v)) clean[k] = v;
    else throw new Error(`bad value for ${k}: ${JSON.stringify(v)}`);
  }
  const cur = readParams();
  const out = {};
  if (typeof cur._comment === "string") out._comment = cur._comment;
  out.params = clean;
  // order === null means "back to the built-in order": drop the override.
  if (body.order === null) { /* omit */ }
  else if (body.order === undefined) { if (cur.order) out.order = cur.order; }
  else if (Array.isArray(body.order) && body.order.every((k) => typeof k === "string" && KEY_RE.test(k))) {
    out.order = body.order;
  } else throw new Error("bad order");
  fs.writeFileSync(PARAMS, JSON.stringify(out, null, 1) + "\n");
  return out;
}

// --- request handler -------------------------------------------------------
const server = http.createServer(async (req, res) => {
  const url = new URL(req.url, `http://${req.headers.host || "localhost"}`);
  const p = decodeURIComponent(url.pathname);

  try {
    if (req.method === "GET" && (p === "/" || p === "/index.html")) {
      return serveFile(res, path.join(PUBLIC, "index.html"));
    }
    if (req.method === "GET" && (p === "/app.js" || p === "/style.css")) {
      return serveFile(res, path.join(PUBLIC, p.slice(1)));
    }
    // anything else in web/public (model.js, future assets) — confined to it
    if (req.method === "GET" && !p.startsWith("/api/") && !p.startsWith("/vendor/")) {
      const f = path.join(PUBLIC, p);
      if (f.startsWith(PUBLIC + path.sep) && fs.existsSync(f) && fs.statSync(f).isFile()) {
        return serveFile(res, f);
      }
    }
    if (req.method === "GET" && (p === "/graph.json" || p === "/api/graph")) {
      const g = ensureGraph();
      if (!g.ok) return sendJSON(res, 500, { error: "graph not available: " + g.error });
      return serveFile(res, GRAPH);
    }
    // Route feedback is generated by hardware/route_feedback.py (make route).
    // Optional: the UI works without it, it just has no routing panel.
    if (req.method === "GET" && (p === "/route-feedback.json" || p === "/api/route-feedback")) {
      if (!fs.existsSync(FEEDBACK)) {
        return sendJSON(res, 404, { error: "no route feedback - run make route" });
      }
      return serveFile(res, FEEDBACK);
    }
    if (req.method === "GET" && p === "/api/seeds") {
      return sendJSON(res, 200, { default: DEFAULT_SEED, seeds: listSeeds() });
    }
    if (req.method === "GET" && p === "/api/seed") {
      const name = safeName(url.searchParams.get("name") || DEFAULT_SEED);
      if (!name) return sendJSON(res, 400, { error: "bad name" });
      const f = seedPath(name);
      if (!f) return sendJSON(res, 404, { error: "no such seed: " + name });
      return serveFile(res, f);
    }
    if (req.method === "GET" && p === "/api/params") {
      const j = readParams();
      return sendJSON(res, 200, {
        file: rel(PARAMS), exists: fs.existsSync(PARAMS),
        params: (j.params && typeof j.params === "object") ? j.params : {},
        order: Array.isArray(j.order) ? j.order : null,
      });
    }
    if ((req.method === "POST" || req.method === "PUT") && p === "/api/params") {
      const body = JSON.parse(await readBody(req) || "{}");
      const out = writeParams(body);
      return sendJSON(res, 200, {
        ok: true, file: rel(PARAMS),
        values: Object.keys(out.params).length,
        order: out.order ? out.order.length : null,
      });
    }
    if (req.method === "POST" && p === "/api/save") {
      const body = JSON.parse(await readBody(req) || "{}");
      const name = safeName(body.name || "placement") || "placement";
      if (!body.positions || typeof body.positions !== "object") {
        return sendJSON(res, 400, { error: "positions required" });
      }
      // Shape is the same as an engine output so render.py / apply.py accept it.
      // No timestamp: this file is tracked, and a re-save of the same placement
      // should be a no-op diff.
      const out = {
        engine: "interactive",
        seed: body.seed || null,
        params: body.params || {},
        pinned: body.pinned || [],
        positions: body.positions,
      };
      const file = path.join(PLACEMENTS, `${name}.json`);
      fs.mkdirSync(PLACEMENTS, { recursive: true });
      fs.writeFileSync(file, JSON.stringify(out, null, 1) + "\n");
      return sendJSON(res, 200, {
        ok: true, file: rel(file), tracked: true,
        render: `make place-render F=${rel(file)}`,
        apply: `make place-apply F=${rel(file)}`,
      });
    }
    if (req.method === "POST" && p === "/api/apply") {
      const body = JSON.parse(await readBody(req) || "{}");
      const file = path.resolve(ROOT, body.file || "");
      const allowed = file.startsWith(LAYOUT + path.sep) || file.startsWith(PLACEMENTS + path.sep);
      if (!allowed || !fs.existsSync(file)) {
        return sendJSON(res, 400, { error: "file must be an existing build/layout/*.json or ui/placement/placements/*.json" });
      }
      const out = path.join(LAYOUT, "board.kicad_pcb");
      const r = spawnSync(PY, [path.join(HERE, "apply.py"), file, out],
        { cwd: ROOT, encoding: "utf8", timeout: 600000, env: process.env });
      // apply.py also turns the DRC into placement feedback (unrouted,
      // clearance, power-channel pinch), so this works on an unrouted board
      // too: move parts, apply, see what the router/DRC would complain about.
      return sendJSON(res, r.status === 0 ? 200 : 500, {
        ok: r.status === 0,
        board: path.relative(ROOT, out),
        feedback: r.status === 0 && fs.existsSync(FEEDBACK)
          ? path.relative(ROOT, FEEDBACK) : null,
        stdout: r.stdout || "",
        stderr: r.stderr || "",
      });
    }
    if (req.method === "GET" && p.startsWith("/vendor/")) {
      const rest = p.slice("/vendor/".length);
      const pkg = rest.split("/")[0];
      if (!VENDOR_PKGS.has(pkg)) return send(res, 403, "forbidden package");
      const file = path.resolve(VENDOR, rest);
      if (!file.startsWith(VENDOR + path.sep)) return send(res, 403, "forbidden path");
      return serveFile(res, file);
    }
    return send(res, 404, "not found: " + p);
  } catch (e) {
    return sendJSON(res, 500, { error: String(e.message || e) });
  }
});

server.listen(PORT, HOST, () => {
  const g = ensureGraph();
  console.log(`TinyUPS interactive placement`);
  console.log(`  http://${HOST === "0.0.0.0" ? "localhost" : HOST}:${PORT}/`);
  console.log(`  root   ${ROOT}`);
  console.log(`  graph  ${g.ok ? GRAPH : "UNAVAILABLE (" + g.error + ")"}`);
  console.log(`  seeds  ${listSeeds().length} (default ${DEFAULT_SEED})`);
});
